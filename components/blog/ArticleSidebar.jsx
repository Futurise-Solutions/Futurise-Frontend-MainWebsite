'use client'

import { useEffect, useState } from "react";
import { Box, Text, VStack, HStack, Icon, useToast } from "@chakra-ui/react";
import { FiLink } from "react-icons/fi";
import { FaLinkedinIn, FaXTwitter } from "react-icons/fa6";

/**
 * The article page's only client island: the table of contents and the share buttons.
 *
 * Everything else on /blog/[slug] — the article text included — is server-rendered. This
 * is interactive by necessity (clipboard, scrollIntoView, scroll position), so it is
 * deliberately the smallest component that covers those three needs.
 *
 * Markup and styling are ported verbatim from BlogDetailPage.jsx. The ADDITION is the
 * scroll-spy: the old TOC had no active state.
 */
const ShareBtn = ({ label, icon, href, onClick }) => (
  <Box
    as={href ? "a" : "button"}
    href={href}
    target={href ? "_blank" : undefined}
    rel={href ? "noopener noreferrer" : undefined}
    onClick={onClick}
    aria-label={label}
    w="38px"
    h="38px"
    display="grid"
    placeItems="center"
    borderRadius="full"
    border="1px solid"
    borderColor="border.subtle"
    color="text.muted"
    transition="all .25s"
    _hover={{ color: "white", borderColor: "brand.400", bg: "rgba(180,160,255,0.12)", transform: "translateY(-2px)" }}
  >
    <Icon as={icon} />
  </Box>
);

export default function ArticleSidebar({ headings = [], title, slug }) {
  const toast = useToast();
  const [activeId, setActiveId] = useState("");

  /* Scroll-spy. Observes the heading elements ArticleBody rendered on the server —
     they carry ids generated by the same slug() rule, so the two line up.
     rootMargin pins the "active" line near the top of the viewport rather than the
     middle, which is what makes a long article's TOC track the reading position. */
  useEffect(() => {
    if (!headings.length) return;
    const els = headings
      .map((h) => document.getElementById(h.id))
      .filter(Boolean);
    if (!els.length) return;

    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((e) => e.isIntersecting)
          .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);
        if (visible[0]) setActiveId(visible[0].target.id);
      },
      { rootMargin: "-90px 0px -70% 0px", threshold: 0 }
    );

    els.forEach((el) => observer.observe(el));
    return () => observer.disconnect();
  }, [headings]);

  // Stable across SSR and hydration; share the canonical article, not a preview host.
  const shareUrl = `https://www.futurisesolutions.com/blog/${slug}`;

  const copyLink = () => {
    navigator.clipboard?.writeText(shareUrl).then(
      () => toast({ title: "Link copied!", status: "success", duration: 2000, position: "top" }),
      () => toast({ title: "Couldn’t copy link", status: "error", duration: 2000, position: "top" })
    );
  };

  return (
    <Box as="aside" w="260px" flexShrink={0} display={{ base: "none", lg: "block" }} position="sticky" top="100px">
      {headings.length > 0 && (
        <Box mb={8}>
          <Text fontSize="xs" fontWeight={700} letterSpacing="0.12em" textTransform="uppercase" color="text.faint" mb={3}>
            On this page
          </Text>
          <VStack align="stretch" spacing={1.5}>
            {headings.map((h) => (
              <Text
                key={h.id}
                as="a"
                href={`#${h.id}`}
                aria-current={activeId === h.id ? "location" : undefined}
                textAlign="left"
                fontSize="sm"
                color={activeId === h.id ? "accent.solid" : "text.muted"}
                pl={h.level === 3 ? 4 : 0}
                _hover={{ color: "accent.solid" }}
                transition="color .2s"
              >
                {h.text}
              </Text>
            ))}
          </VStack>
        </Box>
      )}

      <Box>
        <Text fontSize="xs" fontWeight={700} letterSpacing="0.12em" textTransform="uppercase" color="text.faint" mb={3}>
          Share this article
        </Text>
        <HStack spacing={2}>
          <ShareBtn label="Copy link" icon={FiLink} onClick={copyLink} />
          <ShareBtn
            label="Share on LinkedIn"
            icon={FaLinkedinIn}
            href={`https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(shareUrl)}`}
          />
          <ShareBtn
            label="Share on X"
            icon={FaXTwitter}
            href={`https://twitter.com/intent/tweet?url=${encodeURIComponent(shareUrl)}&text=${encodeURIComponent(title)}`}
          />
        </HStack>
      </Box>
    </Box>
  );
}
